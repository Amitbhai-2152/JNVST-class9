const variationPrefixes = ['सही उत्तर चुनिए:', 'निम्न में से सही विकल्प पहचानिए:', 'सही विकल्प कौन-सा है?', 'उपयुक्त उत्तर चुनें:', 'निम्न प्रश्न का सही उत्तर बताइए:'];
const difficulties = ['easy','easy','medium','medium','medium','hard','hard','hard','challenge','challenge'] as const;

function chapterOf(topicId: string) {
  return chapters.find(c => c.topicIds.includes(topicId as never))?.id ?? '';
}
function subjectOf(topicId: string) {
  if (topicId.startsWith('top_eng')) return 'sub_eng';
  if (topicId.startsWith('top_hin')) return 'sub_hin';
  if (topicId.startsWith('top_math')) return 'sub_math';
  return 'sub_sci';
}

export const generatedQuestions: Question[] = Object.entries(F).flatMap(([topicId, facts]) => {
  const subjectId = subjectOf(topicId);
  const chapterId = chapterOf(topicId);
  return Array.from({length: 10}, (_, i) => {
    const fact = facts[Math.floor(i / 5)];
    const [, answer, d1, d2, d3] = fact;
    const basePrompt = fact[0];
    const text = `${variationPrefixes[i % variationPrefixes.length]} ${basePrompt}`;
    const distractors = [d1, d2, d3];
    const rotate = i % 4;
    const optionsText = [answer, ...distractors].map((v, n) => ({v, n})).sort((a,b) => ((a.n + rotate) % 4) - ((b.n + rotate) % 4)).map(x => x.v);
    const correctIndex = optionsText.indexOf(answer);
    return createQuestion({
      id: `q_${topicId}_${String(i + 1).padStart(2, '0')}`,
      type: 'mcq', subjectId, chapterId, topicId,
      textPlain: text,
      options: optionsText.map((text, n) => ({id: `opt_${n+1}`, text})),
      correctOptionIds: [`opt_${correctIndex + 1}`],
      explanationPlain: `सही उत्तर: ${answer}`,
      difficulty: difficulties[i],
      tags: [topics.find(t => t.id === topicId)?.title ?? topicId]
    });
  });
});

